#!/usr/bin/env python3
"""gen_digits_cj.py — Generate app-ios-android/lib/digits.cj from digits_yilu_serif_bold.json.

TASK U6: Board geometry & YiluSerif-Bold digit outlines.
"""

import hashlib
import json
import os
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA_PATH = HERE / "data" / "digits_yilu_serif_bold.json"
OUT_PATH = HERE.parent / "lib" / "digits.cj"


def main():
    if not DATA_PATH.exists():
        raise FileNotFoundError(f"Data file not found: {DATA_PATH}")

    raw_bytes = DATA_PATH.read_bytes()
    sha256_hash = hashlib.sha256(raw_bytes).hexdigest()
    data = json.loads(raw_bytes.decode("utf-8"))

    digits = data.get("digits", data)

    # Format data for Cangjie
    advances = []
    bboxes = []
    paths = []

    for d in range(10):
        key = str(d)
        if key not in digits:
            raise KeyError(f"Missing digit {key} in {DATA_PATH}")
        item = digits[key]
        advances.append(f"{float(item['advance']):.1f}")
        bb = item["bbox"]
        bboxes.append(f"[{float(bb[0]):.1f}, {float(bb[1]):.1f}, {float(bb[2]):.1f}, {float(bb[3]):.1f}]")
        paths.append(item["path"])

    advances_str = ", ".join(advances)
    bboxes_str = ",\n    ".join(bboxes)
    paths_str = ",\n    ".join(f'"{p}"' for p in paths)

    cj_content = f'''/*
 * Code generated by app-ios-android/scripts/gen_digits_cj.py; DO NOT EDIT.
 * Source: app-ios-android/scripts/data/digits_yilu_serif_bold.json
 * Source SHA256: {sha256_hash}
 */

package ohos_app_cangjie_entry

import std.convert.*

let DIGIT_ADVANCES: Array<Float64> = [
    {advances_str}
]

let DIGIT_BBOXES: Array<Array<Float64>> = [
    {bboxes_str}
]

let DIGIT_PATHS: Array<String> = [
    {paths_str}
]

public func digitAdvance(d: Int64): Float64 {{
    if (d < 0 || d > 9) {{
        return 0.0
    }}
    return DIGIT_ADVANCES[d]
}}

public func digitBBox(d: Int64): Array<Float64> {{
    if (d < 0 || d > 9) {{
        return [0.0, 0.0, 0.0, 0.0]
    }}
    return DIGIT_BBOXES[d]
}}

public func digitPathCommands(d: Int64, originX: Float64, baselineY: Float64, size: Float64, pxPerVp: Float64): String {{
    if (d < 0 || d > 9) {{
        return ""
    }}
    let factor = if (pxPerVp <= 0.0) {{ 3.0 }} else {{ pxPerVp }}
    let s = DIGIT_PATHS[d]
    let sb = StringBuilder()
    let n = s.size
    var i: Int64 = 0
    var isX = true
    var first = true

    while (i < n) {{
        let b = s.get(i).getOrThrow()
        if (b == 32u8 || b == 9u8 || b == 10u8 || b == 13u8) {{
            i = i + 1
            continue
        }}
        let start = i
        while (i < n) {{
            let cb = s.get(i).getOrThrow()
            if (cb == 32u8 || cb == 9u8 || cb == 10u8 || cb == 13u8) {{
                break
            }}
            i = i + 1
        }}
        let tok = s[start..i]
        if (tok == "M" || tok == "L" || tok == "C" || tok == "Q" || tok == "Z") {{
            if (!first) {{
                sb.append(" ")
            }}
            first = false
            sb.append(tok)
            isX = true
        }} else {{
            let v = Float64.parse(tok)
            if (isX) {{
                let x = (originX + v * size / 1000.0) * factor
                sb.append(" ${{x}}")
                isX = false
            }} else {{
                let y = (baselineY + v * size / 1000.0) * factor
                sb.append(" ${{y}}")
                isX = true
            }}
        }}
    }}
    return sb.toString().trimAscii()
}}
'''

    OUT_PATH.write_text(cj_content, encoding="utf-8")
    print(f"Generated {OUT_PATH} (SHA256: {sha256_hash})")


if __name__ == "__main__":
    main()
