#!/bin/bash
# sync_to_keels.sh — sync CJMP source, shared engine/game, levels JSON and assets into a Keels project.
# Usage: mobile/cjmp/scripts/sync_to_keels.sh <keels_project_dir>
#
# Copies only PNGs referenced by code (rawImg("name") in mobile/cjmp/lib/*.cj).
# Removes stale unreferenced PNGs from the project rawfile dirs.
# Fonts: always copies YiluSerif-Regular.otf + YiluSerif-Bold.otf;
#        also copies YiluSans-Regular.otf and YiluSans-Medium.otf if present.
#
# macOS bash 3.2 compatible (no associative arrays, no mapfile).
set -euo pipefail

# ---------------------------------------------------------------------------
# 1. Argument / path setup
# ---------------------------------------------------------------------------
if [ "$#" -ne 1 ]; then
  echo "Usage: $0 <keels_project_dir>" >&2
  exit 1
fi

PROJ_DIR="$1"
if [ ! -d "$PROJ_DIR" ]; then
  echo "Error: target project directory '$PROJ_DIR' does not exist" >&2
  exit 1
fi
PROJ="$(cd "$PROJ_DIR" && pwd)"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
if [ -d "$SCRIPT_DIR/../../entry" ]; then
  REPO="$(cd "$SCRIPT_DIR/../.." && pwd)"
else
  REPO="$(cd "$SCRIPT_DIR/../../.." && pwd)"
fi

# ---------------------------------------------------------------------------
# 2. Copy lib/ (everything in mobile/cjmp/lib)
# ---------------------------------------------------------------------------
mkdir -p "$PROJ/lib"
if [ -d "$REPO/mobile/cjmp/lib" ]; then
  cp -R "$REPO/mobile/cjmp/lib/." "$PROJ/lib/"
fi

# ---------------------------------------------------------------------------
# 3. Generate lib/engine/*.cj and lib/game/*.cj from mobile/shared/src
# ---------------------------------------------------------------------------
rm -rf "$PROJ/lib/engine" "$PROJ/lib/game"
mkdir -p "$PROJ/lib/engine" "$PROJ/lib/game"

for f in "$REPO/mobile/shared/src/engine"/*.cj; do
  [ -f "$f" ] || continue
  base="$(basename "$f")"
  {
    echo "/* GENERATED by mobile/cjmp/scripts/sync_to_keels.sh from mobile/shared/src — do not edit */"
    sed 's/yilu_zip\./ohos_app_cangjie_entry\./g' "$f"
  } > "$PROJ/lib/engine/$base"
done

for f in "$REPO/mobile/shared/src/game"/*.cj; do
  [ -f "$f" ] || continue
  base="$(basename "$f")"
  {
    echo "/* GENERATED by mobile/cjmp/scripts/sync_to_keels.sh from mobile/shared/src — do not edit */"
    sed 's/yilu_zip\./ohos_app_cangjie_entry\./g' "$f"
  } > "$PROJ/lib/game/$base"
done

# ---------------------------------------------------------------------------
# 4. Generate lib/levels_json.cj from mobile/shared/levels/levels.json
# ---------------------------------------------------------------------------
python3 -c "
import json, sys
levels_path = '$REPO/mobile/shared/levels/levels.json'
out_path = '$PROJ/lib/levels_json.cj'
with open(levels_path, 'r', encoding='utf-8') as f:
    data = json.load(f)
minified = json.dumps(data, separators=(',', ':'), ensure_ascii=False)
raw_delim_start = '##\"'
raw_delim_end = '\"##'
if raw_delim_start in minified or raw_delim_end in minified:
    print('Error: raw string delimiter found in minified JSON', file=sys.stderr)
    sys.exit(1)
content = f'''/* GENERATED by mobile/cjmp/scripts/sync_to_keels.sh from mobile/shared/levels/levels.json — do not edit */
package ohos_app_cangjie_entry

public func levelsJsonText(): String {{
    return ##{chr(34)}{minified}{chr(34)}##
}}
'''
with open(out_path, 'w', encoding='utf-8') as f:
    f.write(content)
"

# ---------------------------------------------------------------------------
# 5. Collect referenced PNG names from mobile/cjmp/lib/*.cj
#    regex: rawImg("([A-Za-z0-9_]+)")
# ---------------------------------------------------------------------------
MEDIA_DIR="$REPO/entry/src/main/resources/base/media"

# Build referenced list (sorted unique names, space-separated for shell iteration)
referenced_names="$(grep -h -oE 'rawImg\("([A-Za-z0-9_]+)"\)' "$REPO/mobile/cjmp/lib"/*.cj \
  | grep -oE '"[A-Za-z0-9_]+"' \
  | tr -d '"' \
  | sort -u)"

if [ -z "$referenced_names" ]; then
  echo "Error: no rawImg() references found in mobile/cjmp/lib/*.cj" >&2
  exit 1
fi

# Validate: all referenced PNGs must exist
ref_count=0
for name in $referenced_names; do
  ref_count=$((ref_count + 1))
  if [ ! -f "$MEDIA_DIR/${name}.png" ]; then
    echo "Error: referenced PNG missing: $MEDIA_DIR/${name}.png" >&2
    exit 1
  fi
done

# Collect all PNG names in media dir (without extension)
all_media_names="$(for p in "$MEDIA_DIR"/*.png; do [ -f "$p" ] || continue; basename "$p" .png; done | sort -u)"

# Compute excluded (in media but not referenced)
excluded_list=""
for name in $all_media_names; do
  if ! echo "$referenced_names" | grep -qx "$name"; then
    if [ -z "$excluded_list" ]; then
      excluded_list="$name"
    else
      excluded_list="$excluded_list,$name"
    fi
  fi
done

echo "png=$ref_count referenced, excluded=${excluded_list:-none}"

# ---------------------------------------------------------------------------
# 6. Sync assets into BOTH rawfile dirs
# ---------------------------------------------------------------------------
IOS_RAWFILE="$PROJ/ios/keels/entry/resources/rawfile"
ANDROID_RAWFILE="$PROJ/android/app/src/main/assets/keels/entry/resources/rawfile"

sync_assets_to() {
  local dest="$1"
  mkdir -p "$dest"

  # --- PNGs: only referenced ones ---
  local count_png=0
  for name in $referenced_names; do
    local src="$MEDIA_DIR/${name}.png"
    cp "$src" "$dest/"
    count_png=$((count_png + 1))
  done

  # --- Remove stale unreferenced PNGs (files that exist in media but not referenced) ---
  for name in $all_media_names; do
    if ! echo "$referenced_names" | grep -qx "$name"; then
      if [ -f "$dest/${name}.png" ]; then
        rm -f "$dest/${name}.png"
      fi
    fi
  done

  # --- SVG icons ---
  local count_svg=0
  for s in "$REPO/icons/icon-undo.svg" "$REPO/icons/icon-reset.svg"; do
    if [ -f "$s" ]; then
      cp "$s" "$dest/"
      count_svg=$((count_svg + 1))
    fi
  done

  # --- Fonts: always serif; sans only if present ---
  local count_otf=0
  local fonts_dir="$REPO/mobile/cjmp/fonts"
  for font in \
    "$fonts_dir/YiluSerif-Regular.otf" \
    "$fonts_dir/YiluSerif-Bold.otf"; do
    if [ -f "$font" ]; then
      cp "$font" "$dest/"
      count_otf=$((count_otf + 1))
    fi
  done
  for font in \
    "$fonts_dir/YiluSans-Regular.otf" \
    "$fonts_dir/YiluSans-Medium.otf"; do
    if [ -f "$font" ]; then
      cp "$font" "$dest/"
      count_otf=$((count_otf + 1))
    fi
  done
  if [ -f "$fonts_dir/OFL.txt" ]; then
    cp "$fonts_dir/OFL.txt" "$dest/"
  fi

  echo "Synced to $dest: png=$count_png svg=$count_svg otf=$count_otf"
}

sync_assets_to "$IOS_RAWFILE"
sync_assets_to "$ANDROID_RAWFILE"

# ---------------------------------------------------------------------------
# 7. Summary
# ---------------------------------------------------------------------------
total_otf=0
fonts_dir="$REPO/mobile/cjmp/fonts"
for font in \
  "$fonts_dir/YiluSerif-Regular.otf" \
  "$fonts_dir/YiluSerif-Bold.otf" \
  "$fonts_dir/YiluSans-Regular.otf" \
  "$fonts_dir/YiluSans-Medium.otf"; do
  [ -f "$font" ] && total_otf=$((total_otf + 1))
done

total_svg=2
total_levels=$(python3 -c "import json; print(len(json.load(open('$REPO/mobile/shared/levels/levels.json'))))")

echo "SYNC OK png=$ref_count svg=$total_svg otf=$total_otf levels=$total_levels excluded=${excluded_list:-none}"
