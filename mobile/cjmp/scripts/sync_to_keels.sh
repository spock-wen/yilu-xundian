#!/bin/bash
set -euo pipefail

# Usage: sync_to_keels.sh <keels_project_dir>
if [ "$#" -ne 1 ]; then
  echo "Usage: $0 <keels_project_dir>" >&2
  exit 1
fi

PROJ_DIR="$1"
if [ ! -d "$PROJ_DIR" ]; then
  echo "Error: target project directory '$PROJ_DIR' does not exist" >&2
  exit 1
fi
PROJ="$(cd "$PROJ_DIR" && pwd)"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
if [ -d "$SCRIPT_DIR/../../entry" ]; then
  REPO="$(cd "$SCRIPT_DIR/../.." && pwd)"
else
  REPO="$(cd "$SCRIPT_DIR/../../.." && pwd)"
fi

# a) copy every file in $REPO/mobile/cjmp/lib/ (recursively) into <proj>/lib/ (overwrite)
mkdir -p "$PROJ/lib"
if [ -d "$REPO/mobile/cjmp/lib" ]; then
  cp -R "$REPO/mobile/cjmp/lib/." "$PROJ/lib/"
fi

# b) regenerate <proj>/lib/engine/*.cj and <proj>/lib/game/*.cj from mobile/shared/src
rm -rf "$PROJ/lib/engine" "$PROJ/lib/game"
mkdir -p "$PROJ/lib/engine" "$PROJ/lib/game"

for f in "$REPO/mobile/shared/src/engine"/*.cj; do
  [ -f "$f" ] || continue
  base="$(basename "$f")"
  {
    echo "/* GENERATED by mobile/cjmp/scripts/sync_to_keels.sh from mobile/shared/src — do not edit */"
    sed 's/yilu_zip\./ohos_app_cangjie_entry\./g' "$f"
  } > "$PROJ/lib/engine/$base"
done

for f in "$REPO/mobile/shared/src/game"/*.cj; do
  [ -f "$f" ] || continue
  base="$(basename "$f")"
  {
    echo "/* GENERATED by mobile/cjmp/scripts/sync_to_keels.sh from mobile/shared/src — do not edit */"
    sed 's/yilu_zip\./ohos_app_cangjie_entry\./g' "$f"
  } > "$PROJ/lib/game/$base"
done

# c) generate <proj>/lib/levels_json.cj containing minified levels.json in a raw string
python3 -c "
import json, sys
levels_path = '$REPO/mobile/shared/levels/levels.json'
out_path = '$PROJ/lib/levels_json.cj'
with open(levels_path, 'r', encoding='utf-8') as f:
    data = json.load(f)
minified = json.dumps(data, separators=(',', ':'), ensure_ascii=False)
raw_delim_start = '##\"'
raw_delim_end = '\"##'
if raw_delim_start in minified or raw_delim_end in minified:
    print('Error: raw string delimiter found in minified JSON', file=sys.stderr)
    sys.exit(1)
content = f'''/* GENERATED by mobile/cjmp/scripts/sync_to_keels.sh from mobile/shared/levels/levels.json — do not edit */
package ohos_app_cangjie_entry

public func levelsJsonText(): String {{
    return ##\"{minified}\"##
}}
'''
with open(out_path, 'w', encoding='utf-8') as f:
    f.write(content)
"

# d) sync assets into BOTH ends' rawfile dirs
IOS_RAWFILE="$PROJ/ios/keels/entry/resources/rawfile"
ANDROID_RAWFILE="$PROJ/android/app/src/main/assets/keels/entry/resources/rawfile"

sync_assets_to() {
  local dest="$1"
  mkdir -p "$dest"

  # PNG files from entry/src/main/resources/base/media/*.png
  local count_png=0
  for p in "$REPO/entry/src/main/resources/base/media"/*.png; do
    [ -f "$p" ] || continue
    if command -v rsync >/dev/null 2>&1; then
      rsync -a "$p" "$dest/"
    else
      cp "$p" "$dest/"
    fi
    count_png=$((count_png + 1))
  done

  if [ "$count_png" -ne 41 ]; then
    echo "Error: expected 41 PNGs from $REPO/entry/src/main/resources/base/media, found $count_png" >&2
    exit 1
  fi

  # SVG icons
  local count_svg=0
  for s in "$REPO/icons/icon-undo.svg" "$REPO/icons/icon-reset.svg"; do
    if [ -f "$s" ]; then
      if command -v rsync >/dev/null 2>&1; then
        rsync -a "$s" "$dest/"
      else
        cp "$s" "$dest/"
      fi
      count_svg=$((count_svg + 1))
    fi
  done

  # Fonts
  local count_otf=0
  if [ -d "$REPO/mobile/cjmp/fonts" ]; then
    for font in "$REPO/mobile/cjmp/fonts"/*.otf; do
      if [ -f "$font" ]; then
        if command -v rsync >/dev/null 2>&1; then
          rsync -a "$font" "$dest/"
        else
          cp "$font" "$dest/"
        fi
        count_otf=$((count_otf + 1))
      fi
    done
    if [ -f "$REPO/mobile/cjmp/fonts/OFL.txt" ]; then
      if command -v rsync >/dev/null 2>&1; then
        rsync -a "$REPO/mobile/cjmp/fonts/OFL.txt" "$dest/"
      else
        cp "$REPO/mobile/cjmp/fonts/OFL.txt" "$dest/"
      fi
    fi
  fi

  echo "Synced to $dest: png=$count_png svg=$count_svg otf=$count_otf"
}

sync_assets_to "$IOS_RAWFILE"
sync_assets_to "$ANDROID_RAWFILE"

# e) summary line
total_png=41
total_svg=2
total_otf=0
if [ -d "$REPO/mobile/cjmp/fonts" ]; then
  total_otf=$(find "$REPO/mobile/cjmp/fonts" -maxdepth 1 -name "*.otf" | wc -l)
fi
total_levels=$(python3 -c "import json; print(len(json.load(open('$REPO/mobile/shared/levels/levels.json'))))")

echo "SYNC OK png=$total_png svg=$total_svg otf=$total_otf levels=$total_levels"
